GRANT USAGE ON SCHEMA RELATIONSHIP_DISCOVERY_DB.INTM TO ROLE MDM_DATA_STEWARD;
GRANT USAGE ON SCHEMA RELATIONSHIP_DISCOVERY_DB.LOG TO ROLE MDM_DATA_STEWARD;
GRANT USAGE ON SCHEMA RELATIONSHIP_DISCOVERY_DB.MD TO ROLE MDM_DATA_STEWARD;

GRANT SELECT ON ALL TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.FINAL TO ROLE MDM_DATA_STEWARD;
GRANT SELECT ON ALL TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.INTM TO ROLE MDM_DATA_STEWARD;
GRANT SELECT ON ALL TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.LOG TO ROLE MDM_DATA_STEWARD;
GRANT SELECT ON ALL TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.MD TO ROLE MDM_DATA_STEWARD;

GRANT SELECT ON FUTURE TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.FINAL TO ROLE MDM_DATA_STEWARD;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.INTM TO ROLE MDM_DATA_STEWARD;
