/*======================================================================
  017_SECURITY_IMPLEMENTATION.SQL
  Platform Security – RBAC and Dynamic Data Masking.

  Implements:
    - 4 application roles (least privilege)
    - Future grants for schema growth
    - 3 masking policies (role-aware)
    - Policy application to FINAL + INTM tables

  Does not implement:
    - Row Access Policies
    - ABAC / OAuth / SSO / MFA
======================================================================*/

----------------------------------------------------------------------
-- PHASE 1: Create Application Roles
----------------------------------------------------------------------
USE ROLE SYSADMIN;

CREATE ROLE IF NOT EXISTS MDM_ADMIN
  COMMENT = 'Full MDM platform access including security administration';

CREATE ROLE IF NOT EXISTS MDM_DATA_STEWARD
  COMMENT = 'Read access to metadata, master data, action log and audit history';

CREATE ROLE IF NOT EXISTS MDM_BUSINESS_USER
  COMMENT = 'Read access to FINAL.PRODUCT_MASTER only';

CREATE ROLE IF NOT EXISTS MDM_AUDITOR
  COMMENT = 'Read access to action log, version history and metadata';

----------------------------------------------------------------------
-- PHASE 2: Grants (independent roles, no hierarchy)
-- No grants to SYSADMIN/ACCOUNTADMIN/SECURITYADMIN
----------------------------------------------------------------------

----------------------------------------------------------------------
-- PHASE 3: MDM_ADMIN Grants – Full Database Access
----------------------------------------------------------------------
GRANT USAGE ON DATABASE RELATIONSHIP_DISCOVERY_DB TO ROLE MDM_ADMIN;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RELATIONSHIP_DISCOVERY_DB TO ROLE MDM_ADMIN;
GRANT SELECT ON ALL TABLES IN DATABASE RELATIONSHIP_DISCOVERY_DB TO ROLE MDM_ADMIN;
GRANT INSERT, UPDATE, DELETE ON ALL TABLES IN DATABASE RELATIONSHIP_DISCOVERY_DB TO ROLE MDM_ADMIN;
GRANT CREATE TABLE ON ALL SCHEMAS IN DATABASE RELATIONSHIP_DISCOVERY_DB TO ROLE MDM_ADMIN;
GRANT USAGE ON WAREHOUSE EXERCISE_WAREHOUSE TO ROLE MDM_ADMIN;

GRANT SELECT ON FUTURE TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.LOG TO ROLE MDM_ADMIN;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.INTM TO ROLE MDM_ADMIN;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.FINAL TO ROLE MDM_ADMIN;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RELATIONSHIP_DISCOVERY_DB.MD TO ROLE MDM_ADMIN;

