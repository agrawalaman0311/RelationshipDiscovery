----------------------------------------------------------------------
-- VALIDATION 3: Security Coverage Summary
----------------------------------------------------------------------
SELECT
    'SALE_PRICE' AS PROTECTED_ATTRIBUTE,
    'MASK_SALE_PRICE' AS POLICY_NAME,
    'MDM_ADMIN, MDM_DATA_STEWARD' AS VISIBLE_TO,
    'MDM_BUSINESS_USER, MDM_AUDITOR' AS MASKED_FOR
UNION ALL
SELECT
    'SOURCE_EXECUTION_REFERENCE',
    'MASK_SOURCE_EXECUTION_REFERENCE',
    'MDM_ADMIN, MDM_DATA_STEWARD',
    'MDM_BUSINESS_USER, MDM_AUDITOR'
UNION ALL
SELECT
    'ACTION_SOURCE',
    'MASK_ACTION_SOURCE',
    'MDM_ADMIN, MDM_DATA_STEWARD, MDM_AUDITOR',
    'MDM_BUSINESS_USER';
