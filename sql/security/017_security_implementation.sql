----------------------------------------------------------------------
-- PHASE 7: Dynamic Masking Policy – SALE_PRICE
-- Visible: MDM_ADMIN, MDM_DATA_STEWARD
-- Masked:  MDM_BUSINESS_USER, MDM_AUDITOR
----------------------------------------------------------------------
USE ROLE SYSADMIN;

CREATE OR REPLACE MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_SALE_PRICE
  AS (val NUMBER(18,2))
  RETURNS NUMBER(18,2) ->
  CASE
    WHEN CURRENT_ROLE() IN ('MDM_ADMIN', 'MDM_DATA_STEWARD') THEN val
    ELSE NULL
  END;

----------------------------------------------------------------------
-- PHASE 8: Dynamic Masking Policy – SOURCE_EXECUTION_REFERENCE
-- Visible: MDM_ADMIN, MDM_DATA_STEWARD
-- Masked:  MDM_BUSINESS_USER, MDM_AUDITOR
----------------------------------------------------------------------
CREATE OR REPLACE MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_SOURCE_EXECUTION_REFERENCE
  AS (val VARCHAR)
  RETURNS VARCHAR ->
  CASE
    WHEN CURRENT_ROLE() IN ('MDM_ADMIN', 'MDM_DATA_STEWARD') THEN val
    ELSE '***MASKED***'
  END;

----------------------------------------------------------------------
-- PHASE 9: Dynamic Masking Policy – ACTION_SOURCE
-- Visible: MDM_ADMIN, MDM_DATA_STEWARD, MDM_AUDITOR
-- Masked:  MDM_BUSINESS_USER
----------------------------------------------------------------------
CREATE OR REPLACE MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_ACTION_SOURCE
  AS (val VARCHAR)
  RETURNS VARCHAR ->
  CASE
    WHEN CURRENT_ROLE() IN ('MDM_ADMIN', 'MDM_DATA_STEWARD', 'MDM_AUDITOR') THEN val
    ELSE '***MASKED***'
  END;

----------------------------------------------------------------------
-- PHASE 10: Apply Masking Policies – FINAL.PRODUCT_MASTER
----------------------------------------------------------------------
ALTER TABLE RELATIONSHIP_DISCOVERY_DB.FINAL.PRODUCT_MASTER
  MODIFY COLUMN SALE_PRICE
  SET MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_SALE_PRICE;

ALTER TABLE RELATIONSHIP_DISCOVERY_DB.FINAL.PRODUCT_MASTER
  MODIFY COLUMN SOURCE_EXECUTION_REFERENCE
  SET MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_SOURCE_EXECUTION_REFERENCE;

ALTER TABLE RELATIONSHIP_DISCOVERY_DB.FINAL.PRODUCT_MASTER
  MODIFY COLUMN ACTION_SOURCE
  SET MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_ACTION_SOURCE;

----------------------------------------------------------------------
-- PHASE 11: Apply Masking Policies – INTM.INTM_PRODUCT_MASTER
----------------------------------------------------------------------
ALTER TABLE RELATIONSHIP_DISCOVERY_DB.INTM.INTM_PRODUCT_MASTER
  MODIFY COLUMN SALE_PRICE
  SET MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_SALE_PRICE;

ALTER TABLE RELATIONSHIP_DISCOVERY_DB.INTM.INTM_PRODUCT_MASTER
  MODIFY COLUMN SOURCE_EXECUTION_REFERENCE
  SET MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_SOURCE_EXECUTION_REFERENCE;

ALTER TABLE RELATIONSHIP_DISCOVERY_DB.INTM.INTM_PRODUCT_MASTER
  MODIFY COLUMN ACTION_SOURCE
  SET MASKING POLICY RELATIONSHIP_DISCOVERY_DB.FINAL.MASK_ACTION_SOURCE;

----------------------------------------------------------------------
-- VALIDATION 1: Masking Policy Assignments (per policy)
----------------------------------------------------------------------
SELECT POLICY_NAME, REF_DATABASE_NAME, REF_SCHEMA_NAME, REF_ENTITY_NAME, REF_COLUMN_NAME
FROM TABLE(RELATIONSHIP_DISCOVERY_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(
  POLICY_NAME => 'MASK_SALE_PRICE'
));

SELECT POLICY_NAME, REF_DATABASE_NAME, REF_SCHEMA_NAME, REF_ENTITY_NAME, REF_COLUMN_NAME
FROM TABLE(RELATIONSHIP_DISCOVERY_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(
  POLICY_NAME => 'MASK_SOURCE_EXECUTION_REFERENCE'
));

SELECT POLICY_NAME, REF_DATABASE_NAME, REF_SCHEMA_NAME, REF_ENTITY_NAME, REF_COLUMN_NAME
FROM TABLE(RELATIONSHIP_DISCOVERY_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(
  POLICY_NAME => 'MASK_ACTION_SOURCE'
));

