----------------------------------------------------------------------
-- PHASE 5: MDM_BUSINESS_USER Grants – FINAL Only
----------------------------------------------------------------------
GRANT USAGE ON DATABASE RELATIONSHIP_DISCOVERY_DB TO ROLE MDM_BUSINESS_USER;
