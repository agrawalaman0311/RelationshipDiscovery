        ON COALESCE(e.NORMALIZED_BRAND, s.NORMALIZED_BRAND, i.NORMALIZED_BRAND) = ec.NORMALIZED_BRAND
        AND COALESCE(e.NORMALIZED_PRODUCT_NAME, s.NORMALIZED_PRODUCT_NAME, i.NORMALIZED_PRODUCT_NAME) = ec.NORMALIZED_PRODUCT_NAME
        AND COALESCE(e.NORMALIZED_SIZE, s.NORMALIZED_SIZE, i.NORMALIZED_SIZE) = ec.NORMALIZED_SIZE
