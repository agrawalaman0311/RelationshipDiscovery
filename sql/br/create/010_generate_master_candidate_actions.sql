            WHEN mfr_ecom.PRIORITY_ORDER THEN w.ECOMMERCE_MANUFACTURER
            ELSE NULL
        END AS FALLBACK_MANUFACTURER,

        CASE LEAST(
            CASE WHEN w.ERP_SALE_PRICE IS NOT NULL THEN sp_erp.PRIORITY_ORDER ELSE 999 END,
            CASE WHEN w.SUPPLIER_SALE_PRICE IS NOT NULL THEN sp_sup.PRIORITY_ORDER ELSE 999 END,
            CASE WHEN w.INVENTORY_SALE_PRICE IS NOT NULL THEN sp_inv.PRIORITY_ORDER ELSE 999 END,
            CASE WHEN w.ECOMMERCE_SALE_PRICE IS NOT NULL THEN sp_ecom.PRIORITY_ORDER ELSE 999 END
        )
            WHEN sp_erp.PRIORITY_ORDER  THEN w.ERP_SALE_PRICE
            WHEN sp_sup.PRIORITY_ORDER  THEN w.SUPPLIER_SALE_PRICE
            WHEN sp_inv.PRIORITY_ORDER  THEN w.INVENTORY_SALE_PRICE
            WHEN sp_ecom.PRIORITY_ORDER THEN w.ECOMMERCE_SALE_PRICE
            ELSE NULL
        END AS FALLBACK_SALE_PRICE,

        (COALESCE(w.ERP_DQ_SCORE, 0) + COALESCE(w.SUPPLIER_DQ_SCORE, 0)
         + COALESCE(w.INVENTORY_DQ_SCORE, 0) + COALESCE(w.ECOMMERCE_DQ_SCORE, 0))
        / NULLIF(
            (CASE WHEN w.ERP_DQ_SCORE > 0 THEN 1 ELSE 0 END
             + CASE WHEN w.SUPPLIER_DQ_SCORE > 0 THEN 1 ELSE 0 END
             + CASE WHEN w.INVENTORY_DQ_SCORE > 0 THEN 1 ELSE 0 END
             + CASE WHEN w.ECOMMERCE_DQ_SCORE > 0 THEN 1 ELSE 0 END), 0
        ) AS AVG_RECORD_DQ_SCORE

    FROM wide_entity w
    CROSS JOIN dq_threshold t
    LEFT JOIN brand_priority bp_erp  ON bp_erp.SOURCE_SYSTEM  = 'ERP_PRODUCT'
    LEFT JOIN brand_priority bp_sup  ON bp_sup.SOURCE_SYSTEM  = 'SUPPLIER_PRODUCT'
    LEFT JOIN brand_priority bp_inv  ON bp_inv.SOURCE_SYSTEM  = 'INVENTORY_PRODUCT'
    LEFT JOIN brand_priority bp_ecom ON bp_ecom.SOURCE_SYSTEM = 'ECOMMERCE_PRODUCT'
    LEFT JOIN product_name_priority pn_erp  ON pn_erp.SOURCE_SYSTEM  = 'ERP_PRODUCT'
    LEFT JOIN product_name_priority pn_sup  ON pn_sup.SOURCE_SYSTEM  = 'SUPPLIER_PRODUCT'
    LEFT JOIN product_name_priority pn_inv  ON pn_inv.SOURCE_SYSTEM  = 'INVENTORY_PRODUCT'
    LEFT JOIN product_name_priority pn_ecom ON pn_ecom.SOURCE_SYSTEM = 'ECOMMERCE_PRODUCT'
    LEFT JOIN category_priority cat_erp  ON cat_erp.SOURCE_SYSTEM  = 'ERP_PRODUCT'
    LEFT JOIN category_priority cat_sup  ON cat_sup.SOURCE_SYSTEM  = 'SUPPLIER_PRODUCT'
    LEFT JOIN category_priority cat_inv  ON cat_inv.SOURCE_SYSTEM  = 'INVENTORY_PRODUCT'
    LEFT JOIN category_priority cat_ecom ON cat_ecom.SOURCE_SYSTEM = 'ECOMMERCE_PRODUCT'
    LEFT JOIN manufacturer_priority mfr_erp  ON mfr_erp.SOURCE_SYSTEM  = 'ERP_PRODUCT'
    LEFT JOIN manufacturer_priority mfr_sup  ON mfr_sup.SOURCE_SYSTEM  = 'SUPPLIER_PRODUCT'
    LEFT JOIN manufacturer_priority mfr_inv  ON mfr_inv.SOURCE_SYSTEM  = 'INVENTORY_PRODUCT'
    LEFT JOIN manufacturer_priority mfr_ecom ON mfr_ecom.SOURCE_SYSTEM = 'ECOMMERCE_PRODUCT'
    LEFT JOIN sale_price_priority sp_erp  ON sp_erp.SOURCE_SYSTEM  = 'ERP_PRODUCT'
    LEFT JOIN sale_price_priority sp_sup  ON sp_sup.SOURCE_SYSTEM  = 'SUPPLIER_PRODUCT'
    LEFT JOIN sale_price_priority sp_inv  ON sp_inv.SOURCE_SYSTEM  = 'INVENTORY_PRODUCT'
    LEFT JOIN sale_price_priority sp_ecom ON sp_ecom.SOURCE_SYSTEM = 'ECOMMERCE_PRODUCT'
    LEFT JOIN size_priority sz_erp  ON sz_erp.SOURCE_SYSTEM  = 'ERP_PRODUCT'
    LEFT JOIN size_priority sz_sup  ON sz_sup.SOURCE_SYSTEM  = 'SUPPLIER_PRODUCT'
    LEFT JOIN size_priority sz_inv  ON sz_inv.SOURCE_SYSTEM  = 'INVENTORY_PRODUCT'
    LEFT JOIN size_priority sz_ecom ON sz_ecom.SOURCE_SYSTEM = 'ECOMMERCE_PRODUCT'
),

master_candidates AS (
    SELECT
        sa.*,
        COALESCE(sa.SURVIVED_BRAND, sa.NORMALIZED_BRAND)               AS MASTER_BRAND,
        COALESCE(sa.SURVIVED_PRODUCT_NAME, sa.NORMALIZED_PRODUCT_NAME) AS MASTER_PRODUCT_NAME,
        COALESCE(sa.SURVIVED_SIZE, sa.NORMALIZED_SIZE)                 AS MASTER_SIZE,
        COALESCE(sa.SURVIVED_CATEGORY, sa.FALLBACK_CATEGORY)           AS MASTER_CATEGORY,
        COALESCE(sa.SURVIVED_MANUFACTURER, sa.FALLBACK_MANUFACTURER)   AS MASTER_MANUFACTURER,
        COALESCE(sa.SURVIVED_SALE_PRICE, sa.FALLBACK_SALE_PRICE)       AS MASTER_SALE_PRICE
    FROM survivorship_applied sa
),

final_master_dedup AS (
    SELECT
        mc.*,
        ROW_NUMBER() OVER (
            PARTITION BY UPPER(TRIM(mc.MASTER_BRAND)),
                         UPPER(TRIM(mc.MASTER_PRODUCT_NAME)),
                         UPPER(TRIM(mc.MASTER_SIZE))
            ORDER BY mc.SOURCE_COVERAGE DESC,
                     mc.AVG_RECORD_DQ_SCORE DESC NULLS LAST,
                     LEAST(
                         COALESCE(mc.ERP_PRODUCT_ID, 'ZZZZZZZZ'),
                         COALESCE(mc.SUPPLIER_PRODUCT_ID, 'ZZZZZZZZ'),
                         COALESCE(mc.INVENTORY_PRODUCT_ID, 'ZZZZZZZZ'),
                         COALESCE(mc.ECOMMERCE_PRODUCT_ID, 'ZZZZZZZZ')
                     ) ASC
        ) AS MASTER_DEDUP_RN
    FROM master_candidates mc
),

quality_gate AS (
    SELECT
        MD5_HEX(
            UPPER(TRIM(fm.MASTER_BRAND))
            || '|'
            || UPPER(TRIM(fm.MASTER_PRODUCT_NAME))
            || '|'
            || UPPER(TRIM(fm.MASTER_SIZE))
        ) AS ENTITY_KEY,
        fm.ERP_PRODUCT_ID,
        fm.SUPPLIER_PRODUCT_ID,
        fm.INVENTORY_PRODUCT_ID,
        fm.ECOMMERCE_PRODUCT_ID,
        fm.MASTER_BRAND,
        fm.MASTER_PRODUCT_NAME,
        fm.MASTER_CATEGORY,
        fm.MASTER_MANUFACTURER,
        fm.MASTER_SALE_PRICE,
        fm.MASTER_SIZE,
        fm.SOURCE_COVERAGE,
        fm.AVG_RECORD_DQ_SCORE,
        fm.MASTER_BRAND_SOURCE,
        fm.MASTER_PRODUCT_NAME_SOURCE,
        fm.MASTER_CATEGORY_SOURCE,
        fm.MASTER_MANUFACTURER_SOURCE,
        fm.MASTER_SALE_PRICE_SOURCE,
        fm.MASTER_SIZE_SOURCE
    FROM final_master_dedup fm
    WHERE fm.MASTER_DEDUP_RN = 1
      AND fm.MASTER_BRAND IS NOT NULL AND TRIM(fm.MASTER_BRAND) != ''
      AND fm.MASTER_PRODUCT_NAME IS NOT NULL AND TRIM(fm.MASTER_PRODUCT_NAME) != ''
      AND fm.MASTER_SIZE IS NOT NULL AND TRIM(fm.MASTER_SIZE) != ''
),

uniqueness_guard AS (
    SELECT
        qg.*,
        ROW_NUMBER() OVER (
            PARTITION BY qg.ENTITY_KEY
            ORDER BY qg.SOURCE_COVERAGE DESC,
                     qg.AVG_RECORD_DQ_SCORE DESC
        ) AS UNIQUE_RN
    FROM quality_gate qg
)

SELECT
    'CREATE'                AS ACTION_TYPE,
    'PENDING'               AS ACTION_STATUS,
    'N'                     AS ACTIONED_FLAG,
    ug.ENTITY_KEY,
    ug.ERP_PRODUCT_ID,
    ug.SUPPLIER_PRODUCT_ID,
    ug.INVENTORY_PRODUCT_ID,
    ug.ECOMMERCE_PRODUCT_ID,
    ug.MASTER_BRAND,
    ug.MASTER_PRODUCT_NAME,
    ug.MASTER_CATEGORY,
    ug.MASTER_MANUFACTURER,
    ug.MASTER_SALE_PRICE,
    ug.MASTER_SIZE,
    NULL                    AS DERIVED_PRODUCT_FAMILY,
    NULL                    AS DERIVED_PRODUCT_GROUP,
    NULL                    AS DERIVED_PRODUCT_STATUS,
    'BRAND_SRC:' || COALESCE(ug.MASTER_BRAND_SOURCE, 'FALLBACK')
        || '|NAME_SRC:' || COALESCE(ug.MASTER_PRODUCT_NAME_SOURCE, 'FALLBACK')
        || '|CAT_SRC:' || COALESCE(ug.MASTER_CATEGORY_SOURCE, 'FALLBACK')
        || '|MFR_SRC:' || COALESCE(ug.MASTER_MANUFACTURER_SOURCE, 'FALLBACK')
        || '|PRICE_SRC:' || COALESCE(ug.MASTER_SALE_PRICE_SOURCE, 'FALLBACK')
        || '|SIZE_SRC:' || COALESCE(ug.MASTER_SIZE_SOURCE, 'FALLBACK')
    AS SOURCE_EXECUTION_REFERENCE,
    'P_010_GENERATE_MASTER_CANDIDATE' AS ACTION_SOURCE
FROM uniqueness_guard ug
WHERE ug.UNIQUE_RN = 1
  AND NOT EXISTS (
    SELECT 1
    FROM RELATIONSHIP_DISCOVERY_DB.LOG.ACTION_LOG al
    WHERE al.ACTION_TYPE = 'CREATE'
      AND al.ENTITY_KEY = ug.ENTITY_KEY
);
