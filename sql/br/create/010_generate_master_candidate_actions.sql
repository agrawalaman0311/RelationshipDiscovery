normalized_source AS (
    SELECT
        ss.SOURCE_SYSTEM,
        ss.SOURCE_RECORD_ID,
        ss.BRAND,
        ss.PRODUCT_NAME,
        ss.CATEGORY,
        ss.MANUFACTURER,
        ss.SALE_PRICE,
        ss.SIZE,
        UPPER(TRIM(COALESCE(ss.BRAND, '')))        AS NORMALIZED_BRAND,
        UPPER(TRIM(COALESCE(ss.PRODUCT_NAME, ''))) AS NORMALIZED_PRODUCT_NAME,
        UPPER(TRIM(COALESCE(ss.SIZE, '')))         AS NORMALIZED_SIZE,
        COALESCE(dq.RECORD_DQ_SCORE, 0)           AS RECORD_DQ_SCORE
    FROM RELATIONSHIP_DISCOVERY_DB.INTM.SOURCE_SUPERSET ss
    LEFT JOIN RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RECORD_SUMMARY dq
        ON ss.SOURCE_SYSTEM = dq.SOURCE_SYSTEM
        AND ss.SOURCE_RECORD_ID = dq.SOURCE_RECORD_ID
),

source_dedup AS (
    SELECT
        SOURCE_SYSTEM,
        SOURCE_RECORD_ID,
        BRAND,
        PRODUCT_NAME,
        CATEGORY,
        MANUFACTURER,
        SALE_PRICE,
        SIZE,
        NORMALIZED_BRAND,
        NORMALIZED_PRODUCT_NAME,
        NORMALIZED_SIZE,
        RECORD_DQ_SCORE,
        ROW_NUMBER() OVER (
            PARTITION BY SOURCE_SYSTEM, NORMALIZED_BRAND, NORMALIZED_PRODUCT_NAME, NORMALIZED_SIZE
            ORDER BY RECORD_DQ_SCORE DESC, SOURCE_RECORD_ID ASC
        ) AS DEDUP_RN
    FROM normalized_source
),

