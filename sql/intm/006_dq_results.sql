CREATE TABLE IF NOT EXISTS RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RESULTS (
    DQ_RESULT_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    SOURCE_RECORD_ID VARCHAR(100) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(100) NOT NULL,
    ATTRIBUTE_VALUE VARCHAR(5000),
    DQ_STATUS VARCHAR(20) NOT NULL,
    DQ_SCORE NUMBER(5,2) NOT NULL,
    DQ_MESSAGE VARCHAR(500),
    CREATED_DTTM TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RECORD_SUMMARY (
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    SOURCE_RECORD_ID VARCHAR(100) NOT NULL,
    TOTAL_ATTRIBUTES NUMBER NOT NULL,
    PASSED_ATTRIBUTES NUMBER NOT NULL,
    FAILED_ATTRIBUTES NUMBER NOT NULL,
    RECORD_DQ_SCORE NUMBER(5,2) NOT NULL,
    RECORD_DQ_STATUS VARCHAR(20) NOT NULL,
    CREATED_DTTM TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

INSERT INTO RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RESULTS (SOURCE_SYSTEM, SOURCE_RECORD_ID, ATTRIBUTE_NAME, ATTRIBUTE_VALUE, DQ_STATUS, DQ_SCORE, DQ_MESSAGE)
SELECT
    SS.SOURCE_SYSTEM,
    SS.SOURCE_RECORD_ID,
    R.ATTRIBUTE_NAME,
    CASE R.ATTRIBUTE_NAME
        WHEN 'BRAND' THEN SS.BRAND
        WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
        WHEN 'CATEGORY' THEN SS.CATEGORY
        WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
        WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
        WHEN 'SIZE' THEN SS.SIZE
    END AS ATTRIBUTE_VALUE,
    CASE
        WHEN R.NULL_ALLOWED = 'N' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NULL THEN 'FAIL'
        ELSE 'PASS'
    END AS DQ_STATUS,
    CASE
        WHEN R.IS_CRITICAL = 'Y' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NOT NULL THEN 100
        WHEN R.IS_CRITICAL = 'Y' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NULL THEN 0
        WHEN R.IS_CRITICAL = 'N' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NOT NULL THEN 100
        ELSE 50
    END AS DQ_SCORE,
    CASE
        WHEN R.NULL_ALLOWED = 'N' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NULL THEN 'Critical attribute missing'
        ELSE 'Attribute passed validation'
    END AS DQ_MESSAGE
FROM RELATIONSHIP_DISCOVERY_DB.INTM.SOURCE_SUPERSET SS
CROSS JOIN RELATIONSHIP_DISCOVERY_DB.MD.MD_ATTRIBUTE_DQ_RULES R
WHERE R.ACTIVE_FLAG = 'Y';

INSERT INTO RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RECORD_SUMMARY (SOURCE_SYSTEM, SOURCE_RECORD_ID, TOTAL_ATTRIBUTES, PASSED_ATTRIBUTES, FAILED_ATTRIBUTES, RECORD_DQ_SCORE, RECORD_DQ_STATUS)
SELECT
    SOURCE_SYSTEM,
    SOURCE_RECORD_ID,
    COUNT(*) AS TOTAL_ATTRIBUTES,
    SUM(CASE WHEN DQ_STATUS = 'PASS' THEN 1 ELSE 0 END) AS PASSED_ATTRIBUTES,
    SUM(CASE WHEN DQ_STATUS = 'FAIL' THEN 1 ELSE 0 END) AS FAILED_ATTRIBUTES,
    ROUND(AVG(DQ_SCORE), 2) AS RECORD_DQ_SCORE,
    CASE
        WHEN ROUND(AVG(DQ_SCORE), 2) >= 80 THEN 'PASS'
        WHEN ROUND(AVG(DQ_SCORE), 2) >= 60 THEN 'WARNING'
        ELSE 'FAIL'
    END AS RECORD_DQ_STATUS
FROM RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RESULTS
GROUP BY SOURCE_SYSTEM, SOURCE_RECORD_ID;
