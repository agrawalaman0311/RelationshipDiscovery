CREATE OR REPLACE TABLE RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RESULTS AS
SELECT
    ROW_NUMBER() OVER (ORDER BY SS.SOURCE_SYSTEM, SS.SOURCE_RECORD_ID, R.ATTRIBUTE_NAME) AS DQ_RESULT_ID,
    SS.SOURCE_SYSTEM,
    SS.SOURCE_RECORD_ID,
    R.ATTRIBUTE_NAME,
    CASE R.ATTRIBUTE_NAME
        WHEN 'BRAND' THEN SS.BRAND
        WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
        WHEN 'CATEGORY' THEN SS.CATEGORY
        WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
        WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
        WHEN 'SIZE' THEN SS.SIZE
    END AS ATTRIBUTE_VALUE,
    CASE
        WHEN R.NULL_ALLOWED = 'N' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NULL THEN 'FAIL'
        ELSE 'PASS'
    END AS DQ_STATUS,
    CASE
        WHEN R.IS_CRITICAL = 'Y' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NOT NULL THEN 100
        WHEN R.IS_CRITICAL = 'Y' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NULL THEN 0
        WHEN R.IS_CRITICAL = 'N' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NOT NULL THEN 100
        ELSE 50
    END AS DQ_SCORE,
    CASE
        WHEN R.NULL_ALLOWED = 'N' AND
            CASE R.ATTRIBUTE_NAME
                WHEN 'BRAND' THEN SS.BRAND
                WHEN 'PRODUCT_NAME' THEN SS.PRODUCT_NAME
                WHEN 'CATEGORY' THEN SS.CATEGORY
                WHEN 'MANUFACTURER' THEN SS.MANUFACTURER
                WHEN 'SALE_PRICE' THEN SS.SALE_PRICE::VARCHAR
                WHEN 'SIZE' THEN SS.SIZE
            END IS NULL THEN 'Critical attribute missing'
        ELSE 'Attribute passed validation'
    END AS DQ_MESSAGE,
    CURRENT_TIMESTAMP() AS CREATED_DTTM
FROM RELATIONSHIP_DISCOVERY_DB.INTM.SOURCE_SUPERSET SS
CROSS JOIN RELATIONSHIP_DISCOVERY_DB.MD.MD_ATTRIBUTE_DQ_RULES R
WHERE R.ACTIVE_FLAG = 'Y';

CREATE OR REPLACE TABLE RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RECORD_SUMMARY AS
SELECT
    SOURCE_SYSTEM,
    SOURCE_RECORD_ID,
    COUNT(*) AS TOTAL_ATTRIBUTES,
    SUM(CASE WHEN DQ_STATUS = 'PASS' THEN 1 ELSE 0 END) AS PASSED_ATTRIBUTES,
    SUM(CASE WHEN DQ_STATUS = 'FAIL' THEN 1 ELSE 0 END) AS FAILED_ATTRIBUTES,
    ROUND(AVG(DQ_SCORE), 2) AS RECORD_DQ_SCORE,
    CASE
        WHEN ROUND(AVG(DQ_SCORE), 2) >= 80 THEN 'PASS'
        WHEN ROUND(AVG(DQ_SCORE), 2) >= 60 THEN 'WARNING'
        ELSE 'FAIL'
    END AS RECORD_DQ_STATUS,
    CURRENT_TIMESTAMP() AS CREATED_DTTM
FROM RELATIONSHIP_DISCOVERY_DB.INTM.DQ_RESULTS
GROUP BY SOURCE_SYSTEM, SOURCE_RECORD_ID;
